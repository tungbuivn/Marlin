/*
 * gfx4_font_icons_big.h -- font sinh tu TTF bang tools/ttf2gfxfont.py
 *
 *   font    : MaterialIcons-Regular.ttf
 *   size    : 30 px (em size FreeType)   16 muc xam (4 bit/pixel), KHONG threshold
 *   bpp     : 4
 *   xAdvance: 30 px (EP)  yAdvance: 25 px   base_line: 0 px
 *   do dai  : 1 dai, 4 o, 4 glyph co net, 1232 byte bitmap
 *
 * DOI CODEPOINT (font icon: font nguon khong co glyph o codepoint dich):
 *   U+E000  <-  U+E63E  (font nguon)
 *   U+E001  <-  U+E648  (font nguon)
 *   U+E002  <-  U+EBE1  (font nguon)
 *   U+E003  <-  U+EBE4  (font nguon)
 *
 * yOffset da duoc cong +3 px (--yshift) cho moi glyph.
 * yOffset = tu BASELINE len mep tren bitmap (am = o TREN baseline).
 * yAdvance = chieu cao dong; baseline nam o (yAdvance - base_line) tu mep tren dong.
 *
 * DINH DANG: **KHONG phai Adafruit GFXfont** - day la dinh dang RIENG cua ta, viet
 *   thang theo cach LVGL 8.4 doc bitmap bpp4 (lv_draw_sw_letter.c):
 *   - 4 bit/pixel = 16 muc xam (co antialias). Muc n -> do dam n*17 (0..255),
 *     dung bang _lv_bpp4_opa_table[] cua LVGL.
 *   - bitmap la MOT CHUOI BIT LIEN TUC: bit = row*width + col; col CHAN -> nibble CAO
 *     cua byte, col LE -> nibble THAP. KHONG canh byte theo tung hang.
 *   - so byte moi glyph = ceil(width*height*4/8) = ceil(width*height/2)
 *     (vd glyph 3x10 = 15 byte, khong phai 20 nhu kieu canh hang).
 *   - vi vay driver tra con tro THANG vao mang bitmap, KHONG repack.
 *   Kiem chung: tools/probe_lvgl_font_bitmap_layout.py (67/67 va 253/253 glyph cua
 *   font chuan LVGL deu la 'lien tuc') va tools/test_gfxfont_layout.py.
 *   KHONG dung header nay voi Adafruit_GFX / TFT_eSPI (se ra hinh sai).
 */

