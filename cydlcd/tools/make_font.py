#!/usr/bin/env python3
"""
Generate cydlcd/src/font8x8.h -- an 8x8 pixel ASCII font for the ILI9341 driver.

Why a generator (and not a hand-typed table): the cydlcd firmware must build with NO
external libraries (the build machine has no internet, see cydlcd/README.md), so the
font is stored in PROGMEM as raw bytes. This script renders the characters with Pillow
and packs them, so the table can be regenerated / tweaked (font, size, offsets,
threshold) at any time -- and it prints an ASCII-art dump so the glyph shapes can be
checked without hardware.

Header layout:
    font8x8[95][8]    ASCII 32..126, 8 bytes per char, ROW-MAJOR
    byte = bit0..bit7 -> column 0..7 of that row (bit set = lit pixel)
    Cell is 8 px wide (7 px glyph + 1 px gap) and 8 px tall -> 8 px advance.

Dump check: this script prints a few glyphs at the end.

Usage:  python tools/make_font.py            (writes src/font8x8.h)
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

CELL_W = 8
CELL_H = 8
FONT_NAME = "Lucida Console 11px"          # clean + monospace at a pixel-grid size
FONT_PATH = r"C:\Windows\Fonts\lucon.ttf"  # any monospace TTF works
FONT_SIZE = 11
X_OFFSET = 0         # wide glyphs (M, W, %) use 7 of the 8 columns -> 1 px gap
Y_OFFSET = -2        # caps/digits fill rows 0..6; descenders clip at row 7
THRESHOLD = 96
OUT = Path(__file__).resolve().parent.parent / "src" / "font8x8.h"


def render(ch: str, font) -> list[list[int]]:
    img = Image.new("L", (CELL_W * 3, CELL_H * 3), 0)
    ImageDraw.Draw(img).text((X_OFFSET, Y_OFFSET), ch, font=font, fill=255)
    px = img.load()
    return [[1 if px[x, y] > THRESHOLD else 0 for x in range(CELL_W)] for y in range(CELL_H)]



def pack(rows) -> list[int]:
    out = []
    for row in rows:
        b = 0
        for x, on in enumerate(row):
            if on:
                b |= 1 << x
        out.append(b)
    return out


def art(rows) -> str:
    return "\n".join("   " + "".join("#" if b & (1 << x) else "." for x in range(CELL_W)) for b in rows)


def main() -> None:
    font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
    glyphs = {chr(c): pack(render(chr(c), font)) for c in range(32, 127)}

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// AUTO-GENERATED by cydlcd/tools/make_font.py -- do not edit by hand.",
        f"// {FONT_NAME} ({FONT_PATH}) -> {CELL_W}x{CELL_H} cell, row-major, bit0 = left column.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "static const uint8_t font8x8[95][8] PROGMEM = {",
    ]
    for code in range(32, 127):
        ch = chr(code)
        tag = {32: "space", 39: "quote", 92: "backslash"}.get(code, ch)
        lines.append(f"  {{ {', '.join(f'0x{b:02X}' for b in glyphs[ch])} }},   // {code:3d} '{tag}'")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT} ({len(glyphs)} glyphs, {len(glyphs) * CELL_H} bytes of PROGMEM)")

    for ch in "0123456789ABCXZ:.-%g":
        print(f"'{ch}'\n{art(glyphs[ch])}")


if __name__ == "__main__":
    main()
